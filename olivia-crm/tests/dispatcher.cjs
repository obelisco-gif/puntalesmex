const assert=require('node:assert/strict');
const {prepareCommand}=require('../n8n/dispatcher-command.cjs');
const {prepareResult}=require('../n8n/dispatcher-result.cjs');
const base={dispatch_id:'test-id',phone:'34999000100',phone_number_id:'test-sender',delivery_type:'freeform',body:'Texto exacto decidido por Olivia'};
assert.equal(prepareCommand(base).request.text.body,base.body);
assert.equal(prepareCommand({...base,sender_role:'human'}).route,3);
assert.equal(prepareCommand({...base,kind:'ai_disclosure'}).route,3);
assert.equal(prepareCommand({...base,kind:'image',image_url:'https://example.invalid/image.jpg',caption:'Pie de imagen'}).request.image.caption,'Pie de imagen');
assert.equal(prepareCommand({...base,kind:'image'}).route,4);
assert.equal(prepareCommand({...base,delivery_type:'template',template_name:'test_template',template_language:'es',template_components:[{type:'body',parameters:[{type:'text',text:'Parámetro específico'}]}]}).request.template.components[0].parameters[0].text,'Parámetro específico');
assert.equal(prepareCommand({...base,delivery_type:'template',kind:'human_handoff_alert',template_name:'handoff',template_language:'es',template_components:[]}).route,1);
assert.equal(prepareCommand({...base,body:''}).route,4);
assert.equal(prepareCommand({...base,delivery_type:'unknown'}).route,4);
assert.equal(prepareResult({statusCode:429,body:{error:{code:130429,message:'Limit'}}},base).retry_safe,true);
assert.equal(prepareResult({error:{message:'Timeout',statusCode:504}},base).retry_safe,false);
assert.equal(prepareResult({body:{error:{code:190,message:'Invalid token'}}},base).retry_safe,false);
assert.equal(prepareResult({body:{messages:[{id:'confirmed-id'}]}},base).external_id,'confirmed-id');
assert.equal(prepareResult({},base).external_id,null);
console.log('PASS: exact text, image, disclosure, human reply, template parameters, handoff route, invalid payload, throttling and ambiguous failures.');
